import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { softwarehouseActiveApplicationProjectNames } from "./lib/softwarehouse-project-registry.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const defaultAppsRoot = path.resolve(repoRoot, "..");
const appsRoot = path.resolve(
  process.env.LUCKYSPARROW_APPS_ROOT ?? defaultAppsRoot,
);
const outputDir = path.join(repoRoot, "softwarehouse", "portfolio");

const activeRoots = new Set(["Paperclip_Softwarehouse", ...softwarehouseActiveApplicationProjectNames]);
const knownDeferred = new Set([
  "Aviary",
  "Nest",
  "OpenJarvis",
  "Obiekty",
  "LuckySparrow.ch",
]);
const ignored = new Set([".paperclip-worktrees"]);

function csvCell(value) {
  const text = String(value ?? "");
  return /[",\r\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

function classify(name) {
  if (activeRoots.has(name)) return "stage1_active";
  if (name === "Paperclip") return "inactive_alias";
  if (knownDeferred.has(name)) return "deferred";
  return "parked_or_external";
}

async function main() {
  const entries = await readdir(appsRoot, { withFileTypes: true });
  const projects = [];

  for (const entry of entries) {
    if (!entry.isDirectory() || ignored.has(entry.name)) continue;
    const fullPath = path.join(appsRoot, entry.name);
    const info = await stat(fullPath);
    projects.push({
      name: entry.name,
      status: classify(entry.name),
      path: fullPath.replaceAll("\\", "/"),
      updatedAt: info.mtime.toISOString(),
    });
  }

  projects.sort((left, right) => left.name.localeCompare(right.name));
  const generatedAt = new Date().toISOString();

  const markdown = [
    "# Applications Index",
    "",
    `Generated: ${generatedAt}`,
    "",
    "Canonical Stage 1 location: `C:/Personal/Projekty/Aplikacje/Paperclip_Softwarehouse/softwarehouse/portfolio/`.",
    "",
    "This index is generated by `node scripts/update-softwarehouse-portfolio-index.mjs`.",
    "The script reads the portfolio root but writes only inside `Paperclip_Softwarehouse`; root-level `APPLICATIONS_INDEX.*` files remain forbidden.",
    "",
    "| Application | Status | Workspace | Updated At |",
    "| --- | --- | --- | --- |",
    ...projects.map((project) =>
      `| ${project.name} | ${project.status} | \`${project.path}\` | ${project.updatedAt} |`,
    ),
    "",
  ].join("\n");

  const csv = [
    ["application", "status", "workspace", "updated_at"].join(","),
    ...projects.map((project) =>
      [project.name, project.status, project.path, project.updatedAt]
        .map(csvCell)
        .join(","),
    ),
    "",
  ].join("\n");

  await mkdir(outputDir, { recursive: true });
  await Promise.all([
    writeFile(path.join(outputDir, "APPLICATIONS_INDEX.md"), markdown, "utf8"),
    writeFile(path.join(outputDir, "APPLICATIONS_INDEX.csv"), csv, "utf8"),
  ]);

  console.log(JSON.stringify({
    generatedAt,
    appsRoot,
    outputDir,
    projectCount: projects.length,
    files: [
      path.join(outputDir, "APPLICATIONS_INDEX.md"),
      path.join(outputDir, "APPLICATIONS_INDEX.csv"),
    ],
  }, null, 2));
}

await main();
